#!/usr/bin/env python3
"""Rebuild derived audit snapshots only from independently signed inputs.

``content_signoff.json`` is deliberately never generated by this script.  A
valid signoff has this exact shape (hashes and IDs must be supplied by the
human review workflow):

{
  "schema_version": 1,
  "reviewer": "non-empty reviewer identity",
  "reviewed_at": "2026-07-17T12:00:00Z",
  "source_sha256": {
    "data/en_prompts.jsonl": "64 lowercase hex characters",
    "data/zh_prompts.jsonl": "64 lowercase hex characters"
  },
  "metadata_sha256": "canonical merged report metadata hash",
  "plan_ledger_sha256": "canonical historical plan-ledger hash",
  "approved_prompt_ids": ["all 432 prompt IDs, each exactly once"],
  "metadata_overrides": {
    "optional changed prompt ID": {
      "independent": "是",
      "trace": "无",
      "priority": "P3",
      "analysis": "non-empty independent review conclusion",
      "plan": "non-empty final status or follow-up plan"
    }
  }
}

``metadata_overrides`` is optional.  When present, every listed ID must supply
all five metadata fields.  The signed metadata hash is computed after these
overrides are applied, allowing a stale derived report row to be replaced
without treating that report snapshot as independent review evidence.

The hashes printed by ``--show-signoff-inputs`` are informational only.  That
mode cannot create or approve a signoff.  Normal execution is fail-closed:
all source, report, content-signoff, and rendered-artifact checks complete in
memory before any derived file is changed.
"""

