def reverse_validate_report(
    raw: bytes,
    source: SourceSnapshot,
    expected_metadata_sha256: str,
) -> None:
    text = decode_utf8(raw, "rendered report")
    metadata = parse_report_table(text, source, require_current_prompts=True)
    actual_hash = canonical_sha256(canonical_metadata(metadata, source))
    if actual_hash != expected_metadata_sha256:
        raise AuditError("rendered report metadata changed during round-trip validation")
    for name, digest in source.hashes.items():
        marker = f"- `{name}`: `{digest}`"
        if text.count(marker) != 1:
            raise AuditError(f"rendered report does not contain exactly one current hash for {name}")


def reverse_validate_build(
    raw: bytes,
    source: SourceSnapshot,
    checks_by_id: dict[str, dict[str, bool]],
    signoff: Signoff,
) -> None:
    text = decode_utf8(raw, "rendered build report")
    try:
        table_start = text.index("## 逐条验证清单")
        table_end = text.index("\n## 硬门禁汇总", table_start)
    except ValueError as exc:
        raise AuditError("rendered build is missing the row checklist or summary") from exc
    table_rows = []
    for line in text[table_start:table_end].splitlines():
        if not re.match(r"\|\s*\d+\s*\|", line):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) != 18:
            raise AuditError(f"malformed rendered build row: {line[:120]!r}")
        table_rows.append(cells)
    if len(table_rows) != len(source.rows):
        raise AuditError("rendered build row count mismatch")
    ids = [cells[1].strip("`") for cells in table_rows]
    if ids != [row["prompt_id"] for row in source.rows] or len(ids) != len(set(ids)):
        raise AuditError("rendered build prompt order/ID set mismatch")
    for index, (cells, row) in enumerate(zip(table_rows, source.rows), 1):
        stats = expected_stats(row)
        checks = {
            **checks_by_id[row["prompt_id"]],
            "content": row["prompt_id"] in signoff.approved_ids,
        }
        result = all(checks[name] for name in DELIVERY_HARD_CHECK_NAMES)
        expected = [
            str(index),
            f"`{row['prompt_id']}`",
            row["category"],
            row["level"],
            row["language"],
            str(stats["total_chars"]),
            str(stats["total_words"]),
            str(stats["total_regions"]),
            *["PASS" if checks[name] else "FAIL" for name in DELIVERY_HARD_CHECK_NAMES],
            "OBSERVED" if checks["political_term_observed"] else "CLEAR",
            "OBSERVED" if checks["contact_pattern_observed"] else "CLEAR",
            "PASS" if result else "FAIL",
        ]
        if cells != expected:
            raise AuditError(f"rendered build row mismatch for {row['prompt_id']}")
    for name, digest in source.hashes.items():
        if text.count(f"- `{name}`: `{digest}`") != 1:
            raise AuditError(f"rendered build hash mismatch for {name}")
    passed = sum(
        all(
            ({**checks_by_id[row["prompt_id"]], "content": row["prompt_id"] in signoff.approved_ids})[
                name
            ]
            for name in DELIVERY_HARD_CHECK_NAMES
        )
        for row in source.rows
    )
    expected_status = f"验证结果：**{passed}/{len(source.rows)}"
    if expected_status not in text:
        raise AuditError("rendered build success count is not derived correctly")


def render_manifest(
    source: SourceSnapshot,
    report: ReportInput,
    signoff: Signoff,
    outputs: dict[Path, bytes],
) -> bytes:
    value = {
        "schema_version": 1,
        "reviewed_at": signoff.reviewed_at,
        "reviewer": signoff.reviewer,
        "inputs": {
            "source_sha256": source.hashes,
            "metadata_sha256": report.metadata_sha256,
            "plan_ledger_sha256": report.plan_ledger_sha256,
            "content_signoff_sha256": signoff.sha256,
        },
        "outputs": {
            str(path.relative_to(ROOT)): sha256_bytes(raw)
            for path, raw in sorted(outputs.items(), key=lambda item: str(item[0]))
        },
        "prompt_count": len(source.rows),
    }
    return pretty_json_bytes(value)


def prepare_build(
    source: SourceSnapshot,
    checks_by_id: dict[str, dict[str, bool]],
    report: ReportInput,
    signoff: Signoff,
) -> PreparedBuild:
    outputs = {
        REPORT: render_report(source, report, signoff),
        AUDIT_ROWS: pretty_json_bytes(audit_rows_value(source, report.metadata)),
        PROMPTS_MAP: pretty_json_bytes({row["prompt_id"]: row for row in source.rows}),
        BUILD: render_build(source, checks_by_id, signoff),
    }

    reverse_validate_report(outputs[REPORT], source, report.metadata_sha256)
    rendered_audit = strict_json_loads(
        decode_utf8(outputs[AUDIT_ROWS], "rendered audit_rows"), "rendered audit_rows"
    )
    if rendered_audit != audit_rows_value(source, report.metadata):
        raise AuditError("rendered audit_rows failed round-trip validation")
    rendered_map = strict_json_loads(
        decode_utf8(outputs[PROMPTS_MAP], "rendered prompts_map"), "rendered prompts_map"
    )
    if rendered_map != {row["prompt_id"]: row for row in source.rows}:
        raise AuditError("rendered prompts_map failed round-trip validation")
    reverse_validate_build(outputs[BUILD], source, checks_by_id, signoff)

    manifest = render_manifest(source, report, signoff, outputs)
    parsed_manifest = strict_json_loads(
        decode_utf8(manifest, "rendered manifest"), "rendered manifest"
    )
    if parsed_manifest["prompt_count"] != len(source.rows):
        raise AuditError("rendered manifest failed round-trip validation")
    return PreparedBuild(outputs, manifest, source, report, signoff)


def verify_commit_anchors_unchanged(prepared: PreparedBuild) -> None:
    for path, original in prepared.source.raw.items():
        if path.read_bytes() != original:
            raise AuditError(f"source changed during rebuild: {path}")
    if SIGNOFF.read_bytes() != prepared.signoff.raw:
        raise AuditError("content signoff changed during rebuild")


def verify_precommit_inputs_unchanged(prepared: PreparedBuild) -> None:
    verify_commit_anchors_unchanged(prepared)
    if REPORT.read_bytes() != prepared.report_input.raw:
        raise AuditError("report metadata input changed during rebuild")


def verify_committed_outputs(prepared: PreparedBuild) -> None:
    for path, expected in prepared.outputs.items():
        if path.read_bytes() != expected:
            raise AuditError(f"derived output changed before manifest commit: {path}")


@contextmanager
def process_lock() -> Iterator[None]:
    # Lock the script inode so failed preflight never needs to create a lock file.
    with Path(__file__).open("rb") as handle:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle.fileno(), fcntl.LOCK_UN)


def fsync_directory(path: Path) -> None:
    flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0)
    descriptor = os.open(path, flags)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def stage_if_changed(path: Path, raw: bytes) -> Path | None:
    if path.exists() and path.read_bytes() == raw:
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(raw)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o644)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise
    return temporary


def atomic_commit(prepared: PreparedBuild) -> int:
    staged: dict[Path, Path] = {}
    changed = 0
    try:
        for path, raw in prepared.outputs.items():
            temporary = stage_if_changed(path, raw)
            if temporary is not None:
                staged[path] = temporary
        manifest_temp = stage_if_changed(MANIFEST, prepared.manifest)
        if manifest_temp is not None:
            staged[MANIFEST] = manifest_temp

        # This is the last check before replacing any derived output.
        verify_precommit_inputs_unchanged(prepared)
        for path in DERIVED_PATHS:
            temporary = staged.pop(path, None)
            if temporary is not None:
                os.replace(temporary, path)
                fsync_directory(path.parent)
                changed += 1

        # The manifest is the commit marker.  If an input changed while output
        # files were being replaced, leave the old manifest in place so readers
        # reject the incomplete snapshot.
        verify_commit_anchors_unchanged(prepared)
        verify_committed_outputs(prepared)
        manifest_temp = staged.pop(MANIFEST, None)
        if manifest_temp is not None:
            os.replace(manifest_temp, MANIFEST)
            fsync_directory(MANIFEST.parent)
            changed += 1
        return changed
    finally:
        for temporary in staged.values():
            temporary.unlink(missing_ok=True)


def load_metadata_overrides_file(
    path_text: str,
    source: SourceSnapshot,
) -> dict[str, dict[str, str]]:
    candidate = Path(path_text).expanduser()
    if candidate.is_symlink():
        raise AuditError("metadata overrides path must not be a symbolic link")
    try:
        path = candidate.resolve(strict=True)
        path.relative_to(WORKSPACE)
    except (FileNotFoundError, RuntimeError, ValueError) as exc:
        raise AuditError("metadata overrides path must be an existing file inside the workspace") from exc
    try:
        mode = path.stat().st_mode
    except OSError as exc:
        raise AuditError(f"cannot inspect metadata overrides file: {path}") from exc
    if not stat.S_ISREG(mode):
        raise AuditError("metadata overrides path must be a regular file")
    raw = path.read_bytes()
    value = strict_json_loads(decode_utf8(raw, str(path)), str(path))
    if not isinstance(value, dict):
        raise AuditError("metadata overrides file must contain one JSON object")
    if "metadata_overrides" in value:
        if set(value) != SIGNOFF_REQUIRED_KEYS | {"metadata_overrides"}:
            raise AuditError(
                "metadata overrides signoff draft must contain exactly the signoff fields"
            )
        value = value["metadata_overrides"]
    return parse_metadata_overrides(value, set(source.by_id))


def signoff_inputs(
    source: SourceSnapshot,
    report: ReportInput,
    overrides: dict[str, dict[str, str]],
) -> dict[str, Any]:
    merged_report = apply_metadata_overrides(report, source, overrides)
    return {
        "source_sha256": source.hashes,
        "base_metadata_sha256": report.metadata_sha256,
        "merged_metadata_sha256": merged_report.metadata_sha256,
        "plan_ledger_sha256": report.plan_ledger_sha256,
        "prompt_count": len(source.rows),
        "approved_prompt_ids_required": sorted(source.by_id),
    }


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument(
        "--check",
        action="store_true",
        help="validate and render in memory without changing derived files",
    )
    modes.add_argument(
        "--show-signoff-inputs",
        action="store_true",
        help="print unsigned input hashes and required IDs; never creates a signoff",
    )
    parser.add_argument(
        "--metadata-overrides",
        metavar="PATH",
        help="strict metadata overrides JSON used only with --show-signoff-inputs",
    )
    args = parser.parse_args(argv)
    if args.metadata_overrides and not args.show_signoff_inputs:
        parser.error("--metadata-overrides requires --show-signoff-inputs")
    return args


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        with process_lock():
            source, checks_by_id = load_source_snapshot()
            report = load_report_input(source)
            if args.show_signoff_inputs:
                overrides = (
                    load_metadata_overrides_file(args.metadata_overrides, source)
                    if args.metadata_overrides
                    else {}
                )
                print(
                    json.dumps(
                        signoff_inputs(source, report, overrides),
                        ensure_ascii=False,
                        indent=2,
                    )
                )
                return 0
            signoff = load_signoff(source, report)
            report = apply_metadata_overrides(report, source, signoff.metadata_overrides)
            prepared = prepare_build(source, checks_by_id, report, signoff)
            verify_precommit_inputs_unchanged(prepared)
            if args.check:
                print(
                    f"PASS: {len(source.rows)} rows, signed by {signoff.reviewer}, "
                    "all artifacts round-trip in memory"
                )
                return 0
            changed = atomic_commit(prepared)
            print(f"PASS: committed {changed} changed file(s); manifest written last")
            return 0
    except (AuditError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
