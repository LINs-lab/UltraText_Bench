class AuditError(RuntimeError):
    """Raised when an input or rendered artifact cannot be published safely."""


@dataclass(frozen=True)
class SourceSnapshot:
    raw: dict[Path, bytes]
    hashes: dict[str, str]
    rows: tuple[dict[str, Any], ...]
    by_id: dict[str, dict[str, Any]]


@dataclass(frozen=True)
class ReportInput:
    raw: bytes
    text: str
    sha256: str
    prefix: str
    metadata: dict[str, dict[str, str]]
    metadata_sha256: str
    plan_ledger: tuple[dict[str, Any], ...]
    plan_ledger_sha256: str


@dataclass(frozen=True)
class Signoff:
    raw: bytes
    sha256: str
    reviewer: str
    reviewed_at: str
